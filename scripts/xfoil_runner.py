"""Batch driver for xfoil.exe: run viscous polars for any airfoil, parse results.

Airfoil specs accepted everywhere:
  - "naca2412"                     -> generated by XFOIL's NACA command
  - "s1223", "e423", ...           -> looked up in AeroSandbox's bundled UIUC database
  - path to a Selig-format .dat    -> loaded directly
  - (N, 2) numpy array             -> written to a temp .dat

Each run uses a fresh temp directory so XFOIL's PACC never hits an existing
polar file (which would trigger an interactive append prompt and desync the
command stream).
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

# Windows consoles default to cp1252, which chokes on characters like delta
for _stream in (sys.stdout, sys.stderr):
    if hasattr(_stream, "reconfigure"):
        _stream.reconfigure(encoding="utf-8", errors="replace")

XFOIL_EXE = Path(__file__).resolve().parent.parent / "xfoil" / "xfoil.exe"
POLAR_COLUMNS = ["alpha", "CL", "CD", "CDp", "CM", "Top_Xtr", "Bot_Xtr"]

# XFOIL 6.99's airfoil buffer tops out around 500 points
MAX_INPUT_POINTS = 490


def resolve_airfoil(spec):
    """Return ("naca", digits, name) or ("coords", ndarray, name)."""
    if isinstance(spec, np.ndarray):
        return ("coords", spec, "custom")

    s = str(spec).strip()
    p = Path(s)
    if p.suffix.lower() == ".dat" and p.exists():
        name, coords = read_dat(p)
        return ("coords", coords, name)

    low = s.lower().replace(" ", "")
    if low.startswith("naca") and low[4:].isdigit() and len(low[4:]) in (4, 5):
        return ("naca", low[4:], f"NACA {low[4:]}")

    try:
        import aerosandbox as asb
        af = asb.Airfoil(s)
        coords = np.asarray(af.coordinates, dtype=float)
        if coords is None or len(coords) < 10:
            raise ValueError
        return ("coords", coords, s)
    except Exception as e:
        raise ValueError(
            f"Could not resolve airfoil {s!r}: not a .dat path, not nacaXXXX, "
            f"and not found in the AeroSandbox UIUC database ({e})"
        ) from e


def read_dat(path):
    """Read a Selig-format .dat: name line, then x y pairs TE->LE->TE."""
    lines = Path(path).read_text().splitlines()
    name = lines[0].strip()
    pts = []
    for line in lines[1:]:
        parts = line.split()
        if len(parts) >= 2:
            try:
                pts.append((float(parts[0]), float(parts[1])))
            except ValueError:
                continue
    return name, np.array(pts)


def write_dat(coords, path, name="airfoil"):
    with open(path, "w", newline="\n") as f:
        f.write(f"{name}\n")
        for x, y in coords:
            f.write(f" {x:.6f} {y:.6f}\n")


def build_commands(kind, payload, Re, alphas, ncrit, mach, n_panels, n_iter,
                   dat_name="af.dat", polar_name="polar.txt"):
    cmds = ["PLOP", "G", ""]  # disable the graphics window for batch runs
    if kind == "naca":
        cmds.append(f"NACA {payload}")
    else:
        cmds.append(f"LOAD {dat_name}")
    cmds += ["PPAR", f"N {n_panels}", "", ""]
    cmds += ["OPER", f"VISC {Re:.6g}", f"ITER {n_iter}"]
    if mach:
        cmds.append(f"MACH {mach:.4f}")
    if abs(ncrit - 9.0) > 1e-9:
        cmds += ["VPAR", f"N {ncrit:.3f}", ""]
    cmds += ["PACC", polar_name, ""]

    if isinstance(alphas, tuple) and len(alphas) == 3:
        a0, a1, da = alphas
        cmds.append(f"ASEQ {a0:.4g} {a1:.4g} {da:.4g}")
    else:
        for a in np.atleast_1d(alphas):
            cmds.append(f"ALFA {float(a):.4f}")

    cmds += ["", "QUIT"]
    return "\n".join(cmds) + "\n"


def parse_polar(path):
    path = Path(path)
    empty = {c: np.array([]) for c in POLAR_COLUMNS}
    if not path.exists():
        return empty
    lines = path.read_text().splitlines()
    start = None
    for i, line in enumerate(lines):
        if line.strip().startswith("------"):
            start = i + 1
            break
    if start is None:
        return empty
    rows = []
    for line in lines[start:]:
        parts = line.split()
        if len(parts) >= 7:
            try:
                rows.append([float(x) for x in parts[:7]])
            except ValueError:
                continue
    if not rows:
        return empty
    arr = np.array(rows)
    arr = arr[np.argsort(arr[:, 0])]
    # PACC can log an alpha twice if the sweep revisits it; keep the last pass
    _, idx = np.unique(arr[:, 0], return_index=True)
    arr = arr[idx]
    return {c: arr[:, k] for k, c in enumerate(POLAR_COLUMNS)}


def run_polar(airfoil, Re, alphas=(-4.0, 18.0, 0.5), *, ncrit=9.0, mach=0.0,
              n_panels=200, n_iter=200, xfoil_exe=None, timeout=240,
              verbose=False):
    """Run a viscous XFOIL polar. Returns dict of numpy arrays (POLAR_COLUMNS).

    `alphas` is either (start, stop, step) for an ASEQ sweep or an iterable of
    individual angles. Unconverged points are simply absent from the result.
    """
    exe = Path(xfoil_exe) if xfoil_exe else XFOIL_EXE
    if not exe.exists():
        raise FileNotFoundError(f"xfoil.exe not found at {exe}")

    kind, payload, name = resolve_airfoil(airfoil)
    if kind == "coords" and len(payload) > MAX_INPUT_POINTS:
        raise ValueError(f"{name}: {len(payload)} points exceeds XFOIL's input buffer")

    workdir = Path(tempfile.mkdtemp(prefix="xfoil_run_"))
    try:
        if kind == "coords":
            write_dat(payload, workdir / "af.dat", name)
        cmd_str = build_commands(kind, payload, Re, alphas, ncrit, mach,
                                 n_panels, n_iter)
        try:
            proc = subprocess.run(
                [str(exe)],
                input=cmd_str.encode("ascii", errors="replace"),
                stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                cwd=workdir, timeout=timeout,
            )
            if verbose:
                tail = proc.stdout.decode(errors="replace").splitlines()[-15:]
                print("\n".join(tail))
        except subprocess.TimeoutExpired:
            print(f"WARNING: XFOIL timed out after {timeout}s on {name}; "
                  f"using whatever converged before the kill.", file=sys.stderr)

        polar = parse_polar(workdir / "polar.txt")
        if isinstance(alphas, tuple) and len(alphas) == 3:
            n_req = int(round((alphas[1] - alphas[0]) / alphas[2])) + 1
        else:
            n_req = len(np.atleast_1d(alphas))
        if len(polar["alpha"]) < n_req:
            print(f"note: {name} @ Re={Re:.3g}: {len(polar['alpha'])}/{n_req} "
                  f"points converged (gaps are normal near/past stall)",
                  file=sys.stderr)
        return polar
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


def polar_metrics(polar, cl_targets=(1.0, 1.5, 2.0)):
    """Headline numbers for wing-element selection."""
    out = {}
    cl, cd, alpha = polar["CL"], polar["CD"], polar["alpha"]
    if len(cl) == 0:
        return out
    i_max = int(np.argmax(cl))
    out["CL_max"] = float(cl[i_max])
    out["alpha_CL_max"] = float(alpha[i_max])
    valid = cd > 1e-6
    if valid.any():
        ld = cl[valid] / cd[valid]
        j = int(np.argmax(ld))
        out["LD_max"] = float(ld[j])
        out["CL_at_LD_max"] = float(cl[valid][j])
    # CD at fixed CL, interpolated on the pre-stall (ascending) branch
    pre = slice(0, i_max + 1)
    cl_pre, cd_pre = cl[pre], cd[pre]
    order = np.argsort(cl_pre)
    cl_pre, cd_pre = cl_pre[order], cd_pre[order]
    for tgt in cl_targets:
        key = f"CD_at_CL{tgt:g}"
        if len(cl_pre) >= 2 and cl_pre[0] <= tgt <= cl_pre[-1]:
            out[key] = float(np.interp(tgt, cl_pre, cd_pre))
        else:
            out[key] = None
    return out


def save_polar_csv(polar, path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    header = ",".join(POLAR_COLUMNS)
    data = np.column_stack([polar[c] for c in POLAR_COLUMNS])
    np.savetxt(path, data, delimiter=",", header=header, comments="")


def main():
    ap = argparse.ArgumentParser(description="Run an XFOIL viscous polar.")
    ap.add_argument("airfoil", help="name (s1223, naca2412, ...) or .dat path")
    ap.add_argument("--re", type=float, default=3e5, help="Reynolds number")
    ap.add_argument("--alphas", type=float, nargs=3, default=[-4, 18, 0.5],
                    metavar=("START", "STOP", "STEP"))
    ap.add_argument("--ncrit", type=float, default=9.0)
    ap.add_argument("--mach", type=float, default=0.0)
    ap.add_argument("--n-panels", type=int, default=200)
    ap.add_argument("--iter", type=int, default=200, dest="n_iter")
    ap.add_argument("--out", type=Path, default=None, help="CSV output path")
    ap.add_argument("--verbose", action="store_true")
    args = ap.parse_args()

    polar = run_polar(args.airfoil, args.re, tuple(args.alphas),
                      ncrit=args.ncrit, mach=args.mach, verbose=args.verbose,
                      n_panels=args.n_panels, n_iter=args.n_iter)
    m = polar_metrics(polar)
    print(f"\n{args.airfoil} @ Re={args.re:.3g}, Ncrit={args.ncrit:g}: "
          f"{len(polar['alpha'])} converged points")
    for k, v in m.items():
        print(f"  {k:>14}: {v:.4f}" if isinstance(v, float) else f"  {k:>14}: {v}")
    if args.out:
        save_polar_csv(polar, args.out)
        print(f"saved {args.out}")


if __name__ == "__main__":
    main()
